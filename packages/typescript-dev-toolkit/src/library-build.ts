/**
 * @file
 *
 * The build pipeline of a TypeScript LIBRARY package: one `dist/lib/{cjs,esm}` tree of unbundled modules beside its
 * `.d.cts` / `.d.mts` declarations, the generated `index.ts` barrels, and the generated `package.json` `exports` map.
 *
 * Each step works on the current working folder, which is the package being built. A repository's
 * `scripts/build-*.ts` entry points are thin `wrapCliTask` wrappers around these functions, and its `build` script
 * runs them in order through {@link runBuildSteps}.
 */

